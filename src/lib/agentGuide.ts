import { issuePrefix, newIssueId } from './artefacts.ts'
import { humanDate, sumPoints, todayISO } from './format.ts'
import type { BoardConfig, Epic, Issue, Sprint } from './model.ts'

export const AGENT_GUIDE_PATH = '.scrumit/AGENTS.md'

export interface AgentContext {
  repoName: string
  config: BoardConfig
  issues: Issue[]
  epics: Epic[]
  sprints: Sprint[]
}

/**
 * A one-line pointer a person can drop into a repository-root `AGENTS.md` so an
 * agent finds the real specification. scrumit deliberately does not write that
 * file itself: the root `AGENTS.md` usually belongs to somebody else.
 */
export const AGENT_POINTER = `<!-- scrumit -->
This repository's sprint, board and epic artefacts are markdown files with YAML
front-matter. Read \`.scrumit/AGENTS.md\` before creating, moving or closing any
issue.`

/**
 * The repository-specific half of the guide.
 *
 * The format rules are the same everywhere and live in `llms.txt`; what an agent
 * cannot derive from them is *this* board — where the folders actually are, what
 * the next issue number is, and which epics and sprints already exist. Guessing
 * those is what produces duplicate ids and misplaced files, so they are stated.
 */
export function buildAgentPreamble(ctx: AgentContext): string {
  const { config, issues, epics, sprints } = ctx
  const ids = issues.map((issue) => issue.id)
  const prefix = issuePrefix(ids, config.project)
  const nextId = newIssueId(ids, config.project)
  const open = issues.filter((issue) => issue.status !== 'done')

  const labels = [...new Set(issues.flatMap((issue) => issue.labels))].sort()
  const people = [...new Set(issues.map((issue) => issue.assignee).filter(Boolean))].sort()

  const epicLines =
    epics.length === 0
      ? ['_None yet. Create one with `epics/EPIC-01-<slug>.md`._']
      : epics.map((epic) => {
          const scoped = issues.filter((issue) => issue.epic === epic.id)
          const done = scoped.filter((issue) => issue.status === 'done').length
          return `- \`${epic.id}\` — ${epic.title} (${epic.state}, ${done}/${scoped.length} done)`
        })

  const sprintLines =
    sprints.length === 0
      ? ['_None yet. A sprint is a folder with a `sprint.md` inside it._']
      : sprints.map((sprint) => {
          const scoped = issues.filter((issue) => issue.sprint === sprint.id)
          const window =
            sprint.start && sprint.end
              ? `${humanDate(sprint.start)} to ${humanDate(sprint.end)}`
              : 'no dates'
          const capacity = sprint.capacity === null ? '' : `, capacity ${sprint.capacity} pts`
          const wip =
            sprint.wipSoft == null && sprint.wipHard == null
              ? ''
              : `, WIP ${sprint.wipSoft ?? '–'}/${sprint.wipHard ?? '–'} soft/hard`
          return `- \`${sprint.id}\` — ${sprint.name} (${sprint.state}, ${window}${capacity}${wip}, ${scoped.length} issues, ${sumPoints(scoped)} pts)`
        })

  const columnLines = config.columns.map((column) => {
    const scoped = issues.filter((issue) => issue.status === column.id)
    const bits = [
      `\`${column.id}\` → **${column.name}**`,
      column.wip === null ? 'no WIP limit' : `WIP limit ${column.wip}`,
      ...(column.softWip == null ? [] : [`soft WIP ${column.softWip}`]),
      `${scoped.length} issues, ${sumPoints(scoped)} pts`,
    ]
    if (column.terminal) bits.push('terminal')
    if (column.hidden) bits.push('hidden on the board')
    return `- ${bits.join(' · ')}`
  })

  return `# scrumit artefacts — working agreement for ${ctx.repoName}

Generated by scrumit on ${todayISO()}. Regenerate it from **Settings → AI agents**
after the board changes shape; do not hand-edit this preamble.

## This repository, right now

- **Project:** ${config.project || '_(not set — set it in Settings → Board)_'}
- **Today:** ${todayISO()}
- **Issue id prefix:** \`${prefix}\` · **next free id:** \`${nextId}\`
- **Scale:** ${issues.length} issues (${open.length} open, ${issues.length - open.length} done), ${epics.length} epics, ${sprints.length} sprints

### Directories in use

| Artefact | Directory | Source |
| --- | --- | --- |
| unscheduled issues | \`${config.dirs.backlog}/\` | \`backlog.dir\` |
| sprinted issues | \`${config.dirs.sprints}/<sprint>/\` | \`sprints.dir\` |
| finished issues | \`${config.dirs.archive}/<sprint>/\` | \`archive.dir\` |
| epics | \`${config.dirs.epics}/\` | \`epics.dir\` |
| board settings | \`.scrumit/config.yaml\` | — |

### Columns, in order

${columnLines.join('\n')}

${columnLines.length === 0 ? '' : ''}Sprint length is ${config.sprintLengthDays} days. ${
    config.ceremony ? `Ceremonies: ${config.ceremony}.` : ''
  }

### Epics that exist

${epicLines.join('\n')}

### Sprints that exist

${sprintLines.join('\n')}

### Vocabulary already in use

${
  labels.length === 0
    ? '- No labels yet. Introduce them sparingly; a label nobody filters by is decoration.'
    : `- **Labels:** ${labels.map((label) => `\`${label}\``).join(', ')} — reuse these before inventing new ones.`
}
${
  people.length === 0
    ? '- No assignees recorded yet.'
    : `- **Assignees:** ${people.map((person) => `\`${person}\``).join(', ')} — lowercase hyphenated handles, e.g. \`ana-marin\`.`
}

## The rules

Everything below this line is scrumit's canonical format specification. It is the
same in every repository and it is not advisory.
`
}

/**
 * The specification is a single file at the repository root and is inlined here
 * at build time, so the generated guide and `llms.txt` can never drift apart.
 * It is loaded lazily because it is only needed when somebody asks for it.
 */
export async function buildAgentGuide(ctx: AgentContext): Promise<string> {
  const { default: spec } = await import('../../llms.txt?raw')
  return `${buildAgentPreamble(ctx)}\n---\n\n${spec}`
}
